/**
 * Рисунки детали по граням из skin.art — либо null, если их нет.
 *
 * Пользовательские скины из редактора несут только face и torso; для них
 * функция вернёт ровно перед, а уши и рукава просто не появятся. Ломаться тут
 * нечему: отсутствующий ключ — это отсутствующая грань, а не ошибка.
 */
export function partArt(part, skinArt) {
  if (!part?.art || !skinArt) return null;
  if (typeof part.art === 'string') return skinArt[part.art] ?? null;
  const out = {};
  let есть = false;
  for (const [грань, ключ] of Object.entries(part.art)) {
    const рисунок = skinArt[ключ];
    if (рисунок) { out[грань] = рисунок; есть = true; }
  }
  return есть ? out : null;
}
