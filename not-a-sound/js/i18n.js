  function t(key, vars) {
    const lang = window.Platform ? window.Platform.getLanguage() : 'ru';
    let value = (DICT[lang] && DICT[lang][key]) || DICT.ru[key] || key;
    for (const name of Object.keys(vars || {})) {
      value = value.split('{' + name + '}').join(String(vars[name]));
    }
    return value;
  }

